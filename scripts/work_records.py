#!/usr/bin/env python3
"""Index and check one-file-per-record decisions and open questions.

    work_records.py index        rewrite docs/decisions.md and docs/open-questions.md
    work_records.py check        fail if a record is malformed or an index is stale
    work_records.py next dec|oq  print the next free id

Copy this file into the repository (CI has no plugin installed) and call `check` from the
gate. Standard library only. The constants below are the only thing a project should need
to change.
"""

import re
import sys
from pathlib import Path

DOCS = Path("docs")
DECISIONS = {"dir": DOCS / "decisions", "index": DOCS / "decisions.md", "prefix": "DEC"}
QUESTIONS = {"dir": DOCS / "open-questions", "index": DOCS / "open-questions.md", "prefix": "OQ"}
BACKLOG = Path("backlog.yaml")

DECISION_STATUS = {"accepted", "superseded"}
QUESTION_STATUS = {"open", "resolved", "folded", "parked"}
DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")

GENERATED = (
    "<!-- Generated by scripts/work_records.py from {source}/. Edit the records there and run"
    " `python3 scripts/work_records.py index`; a hand edit here fails the gate. -->\n"
)


def parse_value(raw):
    raw = raw.strip()
    if raw.startswith("[") and raw.endswith("]"):
        return [item.strip().strip("\"'") for item in raw[1:-1].split(",") if item.strip()]
    if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in "\"'":
        return raw[1:-1]
    if raw in ("true", "false"):
        return raw == "true"
    return raw


def read_record(path):
    """Frontmatter is a flat block of `key: value` lines; lists are written `[a, b]`."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        raise ValueError("does not start with a --- frontmatter block")
    end = text.find("\n---\n", 4)
    if end == -1:
        raise ValueError("frontmatter block is not closed")
    fields = {}
    for number, line in enumerate(text[4:end].splitlines(), start=2):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, sep, value = line.partition(":")
        if not sep or not re.fullmatch(r"[a-z_]+", key):
            raise ValueError(f"line {number} is not `key: value`")
        fields[key] = parse_value(value)
    return fields


def load(kind):
    pattern = re.compile(rf"^{kind['prefix']}-(\d+)\.md$")
    records, errors = {}, []
    for path in sorted(kind["dir"].glob("*.md")):
        match = pattern.match(path.name)
        if not match:
            continue
        try:
            fields = read_record(path)
        except ValueError as error:
            errors.append(f"{path}: {error}")
            continue
        if fields.get("id") != path.stem:
            errors.append(f"{path}: id is {fields.get('id')!r}, the file name says {path.stem}")
        records[path.stem] = fields
    return records, errors


def number(record_id):
    return int(record_id.rsplit("-", 1)[1])


def cell(value):
    return str(value or "").replace("|", "\\|").replace("\n", " ")


def as_list(value):
    if value in (None, ""):
        return []
    return value if isinstance(value, list) else [value]


def link(record_id, relative_dir):
    return f"[{record_id}]({relative_dir}/{record_id}.md)"


def render_decisions(decisions):
    rel = DECISIONS["dir"].name
    lines = [
        GENERATED.format(source=DECISIONS["dir"]),
        "# Decisions\n",
        f"One file per decision in [{rel}/]({rel}/), newest first. Grep an id to find the record"
        " and everything that cites it.\n",
        "| ID | Date | Decision | Status |",
        "|---|---|---|---|",
    ]
    ordered = sorted(decisions.items(), key=lambda kv: (kv[1].get("date", ""), number(kv[0])), reverse=True)
    for record_id, fields in ordered:
        status = fields.get("status", "")
        if status == "superseded":
            status = "superseded by " + ", ".join(link(i, rel) for i in as_list(fields.get("superseded_by")))
        lines.append(f"| {link(record_id, rel)} | {fields.get('date', '')} | {cell(fields.get('title'))} | {status} |")
    return "\n".join(lines) + "\n"


def render_questions(questions):
    rel = QUESTIONS["dir"].name
    decisions_rel = DECISIONS["dir"].name
    by_status = {status: [] for status in QUESTION_STATUS}
    for record_id, fields in questions.items():
        by_status.setdefault(fields.get("status", ""), []).append((record_id, fields))

    lines = [
        GENERATED.format(source=QUESTIONS["dir"]),
        "# Open questions\n",
        f"One file per question in [{rel}/]({rel}/). A question keeps its file when it closes; only"
        " its status changes.\n",
        "## Open\n",
        "| ID | Question | Decider | Blocking |",
        "|---|---|---|---|",
    ]
    open_rows = sorted(by_status["open"], key=lambda kv: (not kv[1].get("blocking", False), number(kv[0])))
    for record_id, fields in open_rows:
        blocking = "yes" if fields.get("blocking") else ""
        lines.append(f"| {link(record_id, rel)} | {cell(fields.get('title'))} | {cell(fields.get('decider'))} | {blocking} |")

    lines += ["", "## Parked\n", "| ID | Question |", "|---|---|"]
    for record_id, fields in sorted(by_status["parked"], key=lambda kv: number(kv[0])):
        lines.append(f"| {link(record_id, rel)} | {cell(fields.get('title'))} |")

    lines += ["", "## Closed\n", "| ID | Question | Outcome |", "|---|---|---|"]
    closed = by_status["resolved"] + by_status["folded"]
    for record_id, fields in sorted(closed, key=lambda kv: number(kv[0]), reverse=True):
        if fields.get("status") == "folded":
            outcome = "folded into " + link(fields.get("folded_into", ""), rel)
        else:
            outcome = f"resolved {fields.get('resolved', '')}"
            decision = fields.get("decision")
            if decision:
                outcome += " in " + ", ".join(link(d, decisions_rel) for d in as_list(decision))
        lines.append(f"| {link(record_id, rel)} | {cell(fields.get('title'))} | {outcome} |")
    return "\n".join(lines) + "\n"


def validate(decisions, questions):
    errors = []
    for record_id, fields in decisions.items():
        where = DECISIONS["dir"] / f"{record_id}.md"
        for key in ("date", "title", "status"):
            if not fields.get(key):
                errors.append(f"{where}: missing {key}")
        if fields.get("date") and not DATE.match(str(fields["date"])):
            errors.append(f"{where}: date {fields['date']!r} is not YYYY-MM-DD")
        if fields.get("status") and fields["status"] not in DECISION_STATUS:
            errors.append(f"{where}: status {fields['status']!r} is not one of {sorted(DECISION_STATUS)}")
        if fields.get("status") == "superseded" and not as_list(fields.get("superseded_by")):
            errors.append(f"{where}: superseded without superseded_by")
        for key in ("superseded_by", "amended_by", "amends", "supersedes"):
            for target in as_list(fields.get(key)):
                if target not in decisions:
                    errors.append(f"{where}: {key} names {target}, which has no record")

    for record_id, fields in questions.items():
        where = QUESTIONS["dir"] / f"{record_id}.md"
        for key in ("title", "status"):
            if not fields.get(key):
                errors.append(f"{where}: missing {key}")
        status = fields.get("status")
        if status and status not in QUESTION_STATUS:
            errors.append(f"{where}: status {status!r} is not one of {sorted(QUESTION_STATUS)}")
        if status == "resolved" and not DATE.match(str(fields.get("resolved", ""))):
            errors.append(f"{where}: resolved without a resolved: YYYY-MM-DD date")
        if status == "folded" and fields.get("folded_into") not in questions:
            errors.append(f"{where}: folded without a folded_into naming an existing question")
        for target in as_list(fields.get("decision")):
            if target not in decisions:
                errors.append(f"{where}: decision names {target}, which has no record")
    return errors


def main(argv):
    command = argv[1] if len(argv) > 1 else ""
    decisions, errors = load(DECISIONS)
    questions, question_errors = load(QUESTIONS)
    errors += question_errors

    if command == "next":
        kinds = {"dec": (DECISIONS, decisions), "oq": (QUESTIONS, questions)}
        if len(argv) < 3 or argv[2] not in kinds:
            print("usage: work_records.py next dec|oq", file=sys.stderr)
            return 64
        kind, records = kinds[argv[2]]
        print(f"{kind['prefix']}-{max(map(number, records), default=0) + 1}")
        return 0

    if command not in ("index", "check"):
        print(__doc__, file=sys.stderr)
        return 64

    errors += validate(decisions, questions)
    rendered = {DECISIONS["index"]: render_decisions(decisions), QUESTIONS["index"]: render_questions(questions)}

    if command == "index":
        for path, text in rendered.items():
            path.write_text(text, encoding="utf-8")
    else:
        for path, text in rendered.items():
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                errors.append(f"{path} is stale; run `python3 scripts/work_records.py index`")
        if BACKLOG.exists():
            for line_number, line in enumerate(BACKLOG.read_text(encoding="utf-8").splitlines(), start=1):
                if re.match(r"^\s*status:\s*done\s*(#.*)?$", line):
                    errors.append(f"{BACKLOG}:{line_number}: a done task belongs in backlog-done.yaml")

    for error in errors:
        print(error, file=sys.stderr)
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
